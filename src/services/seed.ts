// Bump this version string whenever stations/trains are updated.
// This triggers an automatic refresh of stations & trains in localStorage
// while preserving existing user bookings and accounts.
const DATA_VERSION = 'v2-ap-ts';

export function initializeSeedData(forceReset = false): void {
  const isInitialized = getFromStorage<boolean>(STORAGE_KEYS.INITIALIZED, false);
  const storedVersion = getFromStorage<string>('data_version', '');
  const versionChanged = storedVersion !== DATA_VERSION;

  if (isInitialized && !forceReset && !versionChanged) {
    return;
  }

  // On version change: refresh only reference data (stations & trains),
  // preserving existing bookings, transactions, and user accounts.
  if (versionChanged && isInitialized && !forceReset) {
    setToStorage(STORAGE_KEYS.STATIONS, INITIAL_STATIONS);
    setToStorage(STORAGE_KEYS.TRAINS, INITIAL_TRAINS);
    setToStorage('data_version', DATA_VERSION);
    return;
  }

  setToStorage(STORAGE_KEYS.STATIONS, INITIAL_STATIONS);
  setToStorage(STORAGE_KEYS.TRAINS, INITIAL_TRAINS);
  setToStorage(STORAGE_KEYS.USERS, INITIAL_USERS);
  setToStorage(STORAGE_KEYS.SAVED_PASSENGERS, INITIAL_SAVED_PASSENGERS);
  setToStorage(STORAGE_KEYS.PAYMENT_METHODS, INITIAL_PAYMENT_METHODS);
  setToStorage(STORAGE_KEYS.BOOKINGS, [] as Booking[]);
  setToStorage(STORAGE_KEYS.TRANSACTIONS, []);
  setToStorage(STORAGE_KEYS.INITIALIZED, true);
  setToStorage('data_version', DATA_VERSION);
}
